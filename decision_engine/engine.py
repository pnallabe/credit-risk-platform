def make_decision(
    request: DecisionRequest,
    *,
    policy_overrides: Optional[Dict[str, Any]] = None,
    # GAP-02: override audit fields — required whenever policy_overrides is non-empty
    override_submitted_by: Optional[str] = None,
    override_approved_by: Optional[str] = None,
    override_justification: Optional[str] = None,
    # GAP-11: set True in simulation/replay contexts — bypasses four-eyes GAP-02 check
    _simulation: bool = False,
) -> DecisionResult:
    """Apply the decision policy and return a ``DecisionResult``.

    Decision tree
    ~~~~~~~~~~~~~
    1. **Fraud reject**      → ``REJECT``        (AA02)
    2. **Fraud review**      → ``MANUAL_REVIEW`` (AA05)
    3. **pd_score < 0.05**   → ``APPROVE``       at base rate
    4. **pd_score ≤ 0.10**   → ``APPROVE``       at risk-priced rate
    5. **pd_score > 0.10**   → ``REJECT``        (AA01)

    Parameters
    ----------
    request:
        Populated :class:`DecisionRequest` instance.
    policy_overrides : dict, optional
        Per-tenant policy cutoff overrides resolved from the Config Registry
        (P2.1).  Supported keys::

            pd_threshold      float  — replaces PD_THRESHOLD_MEDIUM
            pd_threshold_low  float  — replaces PD_THRESHOLD_LOW
            dti_high          float  — replaces DTI_HIGH_THRESHOLD

        Unknown keys are silently ignored so future cutoff additions are
        backwards-compatible.
    _simulation:
        Internal flag for simulation / replay contexts (GAP-11).
        When True, GAP-02 four-eyes validation is skipped;
        no override audit records are generated.
        Must **not** be set True in live production decision paths.

    Returns
    -------
    DecisionResult
        Complete decision with audit fields.
    """
    start_ns = time.perf_counter_ns()

    # P2.1 — Apply per-tenant policy cutoffs when provided
    overrides = policy_overrides or {}

    # GAP-02 — Require four-eyes approval metadata whenever overrides are applied
    # (skipped in simulation context via _simulation=True)
    _override_records: List[Any] = []
    if overrides and not _simulation:
        if (
            override_submitted_by is None
            or override_approved_by is None
            or override_justification is None
            or len(override_justification) < 10
        ):
            raise ValueError(
                "policy_overrides require override_submitted_by, override_approved_by, "
                "and override_justification (min 10 chars)"
            )
        # Four-eyes: submitter != approver
        from compliance.rbac import validate_override_submission
        validate_override_submission(
            submitted_by=override_submitted_by,
            approved_by=override_approved_by,
            justification=override_justification,
        )
        # Build a PolicyOverrideRecord stub for each key so the caller can
        # persist them via audit.override_log.log_override().
        try:
            from audit.override_log import PolicyOverrideRecord
            _approved_at = datetime.now(tz=timezone.utc).isoformat()
            for _k, _v in overrides.items():
                # Determine original value from engine constants
                _original: float
                if _k == "pd_threshold_low":
                    _original = PD_THRESHOLD_LOW
                elif _k == "pd_threshold":
                    _original = PD_THRESHOLD_MEDIUM
                elif _k == "dti_high":
                    _original = DTI_HIGH_THRESHOLD
                else:
                    _original = 0.0
                import uuid as _uuid
                _override_records.append(PolicyOverrideRecord(
                    override_id=str(_uuid.uuid4()),
                    decision_id=request.application_id,
                    tenant_id="",  # filled in by the API layer which knows the tenant
                    override_type=_k,
                    original_value=_original,
                    override_value=float(_v),
                    justification=override_justification,
                    submitted_by=override_submitted_by,
                    approved_by=override_approved_by,
                    approved_at=_approved_at,
                ))
        except ImportError:
            pass  # audit module unavailable in minimal test setups
    _pd_low    = float(overrides.get("pd_threshold_low", PD_THRESHOLD_LOW))
    _pd_medium = float(overrides.get("pd_threshold",     PD_THRESHOLD_MEDIUM))

    # Per-product escalation bands override the generic thresholds (S6-A)
    _product_type = getattr(request, "product_type", None) or overrides.get("product_type")
    if _product_type and "pd_threshold_low" not in overrides and "pd_threshold" not in overrides:
        _esc_low, _esc_high = _load_escalation_bands(_product_type)
        _pd_low    = _esc_low
        _pd_medium = _esc_high

    fraud = request.fraud_result
    credit = request.credit_result
    pricing = request.pricing_result

    # ------------------------------------------------------------------
    # Step 1 — Apply decision tree
    # ------------------------------------------------------------------
    if fraud.fraud_flag == "reject":
        decision = DECISION_REJECT

    elif fraud.fraud_flag == "manual_review":
        decision = DECISION_MANUAL_REVIEW

    elif credit.pd_score < _pd_low:
        decision = DECISION_APPROVE

    elif credit.pd_score <= _pd_medium:
        # Within escalation band → MANUAL_REVIEW; generic path → APPROVE
        if _product_type:
            decision = DECISION_MANUAL_REVIEW
        else:
            decision = DECISION_APPROVE

    else:
        decision = DECISION_REJECT

    # ------------------------------------------------------------------
    # S4-A — Post-decision Conditional Approval check
    # ------------------------------------------------------------------
    # If pd_score <= 0.10 (risk-acceptable) but soft conditions fire,
    # downgrade APPROVE to CONDITIONAL.
    # Fraud/MANUAL_REVIEW decisions are never overridden.
    # ------------------------------------------------------------------
    if decision == DECISION_APPROVE and credit.pd_score <= 0.10:
        _features = getattr(request, "features", {}) or {}
        _income_verified = bool(_features.get("income_verified", True))
        _dti = request.debt_to_income_ratio
        _num_open = request.num_open_accounts
        _collateral_coverage = float(_features.get("collateral_coverage_ratio", 0.0))
        _has_collateral = bool(_features.get("collateral_value"))

        _early_conditions: List[Any] = []
        try:
            from decision_engine.conditions import Condition
            if not _income_verified:
                _early_conditions.append(Condition(
                    condition_type="INCOME_VERIFICATION_REQUIRED",
                    description="Income has not been verified. Verification required before funding.",
                ))
            if 0.43 <= _dti <= 0.50:
                _early_conditions.append(Condition(
                    condition_type="REDUCED_LIMIT",
                    description=f"DTI of {_dti:.2f} is elevated. Reduced credit limit recommended.",
                ))
            if _has_collateral and 0 < _collateral_coverage < 1.0:
                _early_conditions.append(Condition(
                    condition_type="COLLATERAL_REQUIRED",
                    description=(
                        f"Collateral coverage ratio of {_collateral_coverage:.2f} is below 1.0. "
                        "Additional collateral or appraisal required."
                    ),
                    min_coverage_ratio=1.0,
                ))
            if _num_open < 3:
                _early_conditions.append(Condition(
                    condition_type="ADDITIONAL_DOCUMENTATION",
                    description="Thin credit file (fewer than 3 open trades). Additional documentation required.",
                    doc_types=["bank_statements", "alternative_credit_data"],
                ))
        except ImportError:
            pass

        if _early_conditions:
            decision = DECISION_CONDITIONAL

    # ------------------------------------------------------------------
    # Step 2 — Build loan terms (only meaningful for APPROVE)
    # ------------------------------------------------------------------
    if decision == DECISION_APPROVE:
        rate = pricing.recommended_rate
        monthly = _monthly_payment(request.loan_amount, rate, request.loan_term_months)
        loan_terms: Dict = {
            "loan_amount": request.loan_amount,
            "loan_term_months": request.loan_term_months,
            "annual_rate_pct": rate,
            "monthly_payment": monthly,
            "expected_loss": pricing.expected_loss,
            "expected_profit": pricing.expected_profit,
            "profitability_flag": pricing.profitability_flag,
        }
        recommended_rate: Optional[float] = rate
    else:
        loan_terms = {}
        recommended_rate = None

    # ------------------------------------------------------------------
    # Step 3 — Collect reason codes
    # ------------------------------------------------------------------
    reason_codes = _collect_reason_codes(
        decision=decision,
        fraud_result=fraud,
        credit_result=credit,
        debt_to_income_ratio=request.debt_to_income_ratio,
        num_open_accounts=request.num_open_accounts,
    )

    # ------------------------------------------------------------------
    # Step 4 — Compute latency and timestamp
    # ------------------------------------------------------------------
    elapsed_ms = int((time.perf_counter_ns() - start_ns) / 1_000_000)
    decision_timestamp = datetime.now(tz=timezone.utc)

    # S4-A — Generate alternative structures for pure rejections
    _alt_structures: List[Any] = []
    if decision == DECISION_REJECT:
        try:
            from decision_engine.alternative_structures import generate_alternatives
            _alt_structures = generate_alternatives(
                request=request,
                pd_score=credit.pd_score,
                decision=decision,
            )
        except Exception as _alt_exc:
            log.warning("Alternative structures generation failed (non-fatal): %s", _alt_exc)

    # S4-A — conditions populated during conditional approval path
    # _early_conditions was built above if decision == CONDITIONAL;
    # fall back to empty list otherwise.
    _conditions: List[Any] = locals().get("_early_conditions", [])

    return DecisionResult(
        application_id=request.application_id,
        decision=decision,
        recommended_rate=recommended_rate,
        loan_terms=loan_terms,
        reason_codes=reason_codes,
        decision_timestamp=decision_timestamp,
        decision_latency_ms=elapsed_ms,
        override_records=_override_records,
        conditions=_conditions,
        alternative_structures=_alt_structures,
    )


