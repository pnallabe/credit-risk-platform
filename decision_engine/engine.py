@dataclass
class ConditionalTerms:
    """Terms for a conditional approval decision.

    Populated only when decision == DECISION_CONDITIONAL.
    Generated by the post-decision override workflow (referral resolution),
    not by the automated pipeline.
    """

    max_loan_amount: Optional[float] = None      # USD cap on approval
    required_collateral: Optional[str] = None    # e.g. "vehicle title"
    co_signer_required: bool = False             # True if co-signer required
    rate_premium_pct: Optional[float] = None     # additional rate premium (%)
    additional_conditions: Optional[str] = None  # free-text


# ---------------------------------------------------------------------------
# Data classes
